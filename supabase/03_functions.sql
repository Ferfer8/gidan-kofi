-- ---------------------------------------------------------------------
-- seed_daily_counts: today's made numbers (the demo reset). A normal run only fills options that have no row today.
--    seed_daily_counts(true) puts today back to these numbers (nothing sold, wasted or carried in,
--    and today's batch log cleared). Frozen stock is not put back.
-- ---------------------------------------------------------------------
create or replace function public.seed_daily_counts(p_reset boolean default false)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_today date := public.business_today();
  v_rows  integer;
begin
  insert into public.daily_counts (size_id, day, made, sold, wasted, carried_in, carried_over)
  select s.id, v_today,
         case lower(m.name)                  -- a realistic morning bake
           when 'butter croissant' then 24
           when 'chocolate croissant' then 18
           when 'cinnamon roll' then 12
           when 'pistachio cookie' then 12
           when 'banana bread' then 8
           when 'date cake' then 8
           when 'chicken pesto sandwich' then 10
           when 'halloumi wrap' then 8
           when 'fruit cup' then 10
           when 'greek yogurt parfait' then 8
           else 12
         end,
         0, 0, 0, 0
  from public.item_sizes s
  join public.menu_items m on m.id = s.menu_item_id
  where m.tracking = 'made_daily'
  on conflict (size_id, day) do update
    set made = excluded.made, sold = 0, wasted = 0, carried_in = 0, carried_over = 0,
        leftover = null, leftovers_saved_at = null, leftovers_by = null
    where p_reset;
  get diagnostics v_rows = row_count;

  if p_reset then
    delete from public.kitchen_batches where public.business_date(created_at) = v_today;
  end if;
  return v_rows;
end;
