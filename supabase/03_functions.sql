returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.staff
    where is_demo_login
      and role = 'manager'
      and status = 'active'
      and email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

