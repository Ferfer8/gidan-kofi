-- ---------------------------------------------------------------------
-- get_pos_menu(p_counter_id): the same as before, but unavailable choices are left out and a counter starts at
-- the item's own number, else the group's
-- ---------------------------------------------------------------------
create or replace function public.get_pos_menu(p_counter_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_today   date := public.business_today();
  v_counter uuid;
  v_next    integer;
  v_tax     jsonb;
  v_rules   jsonb;
  v_details jsonb;
  v_receipts jsonb;
  v_result  jsonb;
begin
  -- the next order number for this counter today (not saved until an order is charged)
  select id into v_counter from public.counters where id = p_counter_id;
  if v_counter is null then raise exception 'That counter does not exist'; end if;
  select coalesce(max(order_number), 0) + 1 into v_next
  from public.orders where counter_id = v_counter and order_date = v_today;

  select tax, discount_rules, details, receipts into v_tax, v_rules, v_details, v_receipts from public.settings limit 1;

  with opts as (
    select s.id, s.menu_item_id, s.label, s.price, s.sort_order,
           case m.tracking
             when 'stock' then (select floor(f.quantity)::int from public.stock_items f where f.id = s.stock_item_id)
             -- carried in + made - sold - wasted - carried over (nothing logged yet today = 0 left)
             when 'made_daily' then coalesce((select greatest(d.carried_in + d.made - d.sold - d.wasted - d.carried_over, 0) from public.daily_counts d where d.size_id = s.id and d.day = v_today), 0)
           end as left_count,
           case when m.tracking = 'stock' then s.stock_item_id end as stock_id,
           case when m.tracking = 'stock' then (select f.sku from public.stock_items f where f.id = s.stock_item_id) end as sku
    from public.item_sizes s
    join public.menu_items m on m.id = s.menu_item_id
    where m.on_menu
  )
  select jsonb_build_object(
    'categories', (
      select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name, 'colour', c.colour, 'sort_order', c.sort_order) order by c.sort_order), '[]'::jsonb)
      from public.categories c
    ),
    'items', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', m.id,
        'name', m.name,
        'description', m.description,
        'category_id', m.category_id,
        'image_url', m.image_url,
        'served', m.served,
        'allergens', to_jsonb(m.allergens),
        'cold_extra', m.cold_extra,
        'tracking', m.tracking,
        'sort_order', m.sort_order,
        'skus', (select coalesce(jsonb_agg(o.sku), '[]'::jsonb) from opts o where o.menu_item_id = m.id and o.sku is not null),
        'options', (
          select jsonb_agg(jsonb_build_object('id', o.id, 'label', o.label, 'price', o.price, 'sort_order', o.sort_order, 'left', o.left_count, 'stock_id', o.stock_id) order by o.sort_order)
          from opts o where o.menu_item_id = m.id
        )
      ) order by c.sort_order, m.sort_order, m.name), '[]'::jsonb)
      from public.menu_items m
      join public.categories c on c.id = m.category_id
      where m.on_menu and exists (select 1 from opts o where o.menu_item_id = m.id)
    ),
    'modifier_groups', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', g.id, 'name', g.name, 'selection', g.selection, 'required', g.required, 'sort_order', g.sort_order,
        'counter_min', g.counter_min, 'counter_max', g.counter_max, 'counter_price', g.counter_price,
        'modifiers', (
          select coalesce(jsonb_agg(jsonb_build_object('id', x.id, 'name', x.name, 'extra_price', x.extra_price, 'is_default', x.is_default, 'sort_order', x.sort_order) order by x.sort_order, x.name), '[]'::jsonb)
          from public.modifiers x where x.group_id = g.id and x.available
        )
      ) order by g.sort_order), '[]'::jsonb)
      from public.modifier_groups g
    ),
    'modifier_group_links', (
      select coalesce(jsonb_agg(jsonb_build_object('group_id', l.group_id, 'menu_item_id', l.menu_item_id, 'category_id', l.category_id, 'default_count', coalesce(l.default_count, (select g2.counter_default from public.modifier_groups g2 where g2.id = l.group_id)))), '[]'::jsonb)
      from public.modifier_group_links l
    ),
    'settings', jsonb_build_object(
      'vat_rate', coalesce((v_tax ->> 'vatRate')::numeric, 5),
      'prices_include_vat', coalesce((v_tax ->> 'pricesIncludeVat')::boolean, false),
      'bag_price', coalesce((v_tax ->> 'bagPrice')::numeric, 0.5),
      'ask_about_bag', coalesce((v_tax ->> 'askAboutBag')::boolean, true),
      'max_manual_percent', coalesce((v_rules ->> 'maxManualPercent')::numeric, 50),
      'reason_required', coalesce((v_rules ->> 'reasonRequired')::boolean, true),
      'cafe_name', coalesce(v_details ->> 'name', 'Gidan Kofi'),
      'address', coalesce(v_details ->> 'address', ''),
      'trn', coalesce(v_details ->> 'trn', ''),
      'receipt_footer', coalesce(v_receipts ->> 'footer', ''),
      'auto_print', coalesce((v_receipts ->> 'autoPrint')::boolean, true),
      'receipt_prefix', coalesce(v_receipts ->> 'prefix', 'GK'),
      'time_zone', public.business_time_zone(),
      'business_day_ends', public.business_day_ends()
    ),
    'next_order_number', v_next,
    'day_closed', exists (select 1 from public.day_closings where counter_id = v_counter and closing_date = v_today and reopened_at is null)
  ) into v_result;

  return v_result;
end;
$$;

