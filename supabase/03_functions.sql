create or replace function public.save_menu_item_with_stock(
  p_item jsonb,
  p_sizes jsonb,
  p_delete_stock_ids uuid[] default '{}'
)
returns uuid
language plpgsql
set search_path = public
as $$
declare
  v_id         uuid := (p_item ->> 'id')::uuid;
  v_name       text := p_item ->> 'name';
  v_tracking   text := coalesce(p_item ->> 'tracking', 'none');
  v_served     text := nullif(p_item ->> 'served', '');
  v_cold_extra numeric := coalesce(nullif(p_item ->> 'cold_extra', '')::numeric, 0);
  v_is_drink   boolean;
  v_keep_ids   uuid[];
  v_size       jsonb;
  v_size_id    uuid;
  v_label      text;
  v_stock_id   uuid;
  v_stock_type text;
  v_stock_name text;
begin
  if not public.is_manager() then
    raise exception 'Only managers can save menu items';
  end if;

  if v_tracking not in ('none', 'stock', 'made_daily') then
    raise exception 'Unknown tracking option: %', v_tracking;
  end if;

  -- "Served" is only for drinks: other items always have no served setting and no extra for cold
  select exists (select 1 from public.categories where id = (p_item ->> 'category_id')::uuid and name = 'Drinks') into v_is_drink;
  if v_is_drink then
    if v_served is null or v_served not in ('hot', 'cold', 'both') then
      raise exception 'Choose Hot, Cold or Hot & cold for %', v_name;
    end if;
    if v_served <> 'both' then
      v_cold_extra := 0;
    end if;
  else
    v_served := null;
    v_cold_extra := 0;
  end if;
  if v_cold_extra < 0 then
    raise exception 'The extra for cold cannot be below 0';
  end if;

  -- the item
  if exists (select 1 from public.menu_items where id = v_id) then
    update public.menu_items
    set category_id = (p_item ->> 'category_id')::uuid,
        name = v_name,
        description = nullif(p_item ->> 'description', ''),
        allergens = coalesce(array(select jsonb_array_elements_text(p_item -> 'allergens')), '{}'),
        on_menu = coalesce((p_item ->> 'on_menu')::boolean, true),
        tracking = v_tracking,
        served = v_served,
        cold_extra = v_cold_extra
    where id = v_id;
  else
    insert into public.menu_items (id, category_id, name, description, allergens, on_menu, sort_order, tracking, served, cold_extra)
    values (
      v_id,
      (p_item ->> 'category_id')::uuid,
      v_name,
      nullif(p_item ->> 'description', ''),
      coalesce(array(select jsonb_array_elements_text(p_item -> 'allergens')), '{}'),
      coalesce((p_item ->> 'on_menu')::boolean, true),
      coalesce((p_item ->> 'sort_order')::int, 0),
      v_tracking,
      v_served,
      v_cold_extra
    );
  end if;

  if coalesce((p_item ->> 'set_image')::boolean, false) then
    update public.menu_items
    set image_url = p_item ->> 'image_url',
        image_original_url = p_item ->> 'image_original_url',
        image_crop = nullif(p_item -> 'image_crop', 'null'::jsonb)
    where id = v_id;
  end if;

  -- options that were removed (and the stock items the manager chose to delete with them)
  select coalesce(array_agg((s ->> 'id')::uuid) filter (where s ->> 'id' is not null), '{}')
  into v_keep_ids
  from jsonb_array_elements(p_sizes) s;

  delete from public.stock_items
  where id = any (p_delete_stock_ids)
    and id in (select stock_item_id from public.item_sizes
               where menu_item_id = v_id and id <> all (v_keep_ids));

  delete from public.item_sizes where menu_item_id = v_id and id <> all (v_keep_ids);

  -- start with no links: they are set again below, so a stock item can move between this item's options
  update public.item_sizes set stock_item_id = null where menu_item_id = v_id;

  -- the options
  for v_size in select * from jsonb_array_elements(p_sizes)
  loop
    v_label := v_size ->> 'label';
    v_size_id := (v_size ->> 'id')::uuid;

    if v_size_id is not null then
      update public.item_sizes
      set label = v_label,
          price = (v_size ->> 'price')::numeric,
          sort_order = (v_size ->> 'sort_order')::int
      where id = v_size_id and menu_item_id = v_id;
    end if;

    if v_size_id is null or not found then
      insert into public.item_sizes (menu_item_id, label, price, sort_order)
      values (v_id, v_label, (v_size ->> 'price')::numeric, (v_size ->> 'sort_order')::int)
      returning id into v_size_id;
    end if;

    -- its stock link
    v_stock_id := nullif(v_size ->> 'stock_item_id', '')::uuid;

    if v_tracking = 'stock' then
      if v_stock_id is null and jsonb_typeof(v_size -> 'new_stock') = 'object' then
        v_stock_name := case when lower(v_label) = 'regular' then v_name else v_name || ' · ' || v_label end;
        insert into public.stock_items (name, type, unit, quantity, low_at)
        values (
          v_stock_name,
          'retail',
          v_size #>> '{new_stock,unit}',
          (v_size #>> '{new_stock,quantity}')::numeric,
          (v_size #>> '{new_stock,low_at}')::numeric
        )
        returning id into v_stock_id;
      end if;

      if v_stock_id is null then
        raise exception '% needs a stock item (choose one, or create a new one)', v_label;
      end if;

      select type into v_stock_type from public.stock_items where id = v_stock_id;
      if v_stock_type is distinct from 'retail' then
        raise exception 'An item sold from stock needs a Retail stock item (%)', v_label;
      end if;

    elsif v_tracking = 'made_daily' then
      if v_stock_id is not null then
        select type into v_stock_type from public.stock_items where id = v_stock_id;
        if v_stock_type is distinct from 'frozen_bakery' then
          raise exception '"Baked from" must be a Frozen bakery stock item (%)', v_label;
        end if;
      end if;

    else
      v_stock_id := null;
    end if;

    if v_stock_id is not null then
      if exists (select 1 from public.item_sizes where stock_item_id = v_stock_id and id <> v_size_id) then
        raise exception 'That stock item is already used by another menu option (%)', v_label;
      end if;
      update public.item_sizes set stock_item_id = v_stock_id where id = v_size_id;
    end if;
  end loop;

  return v_id;
end;
$$;

revoke all on function public.save_menu_item_with_stock(jsonb, jsonb, uuid[]) from public, anon, authenticated;
grant execute on function public.save_menu_item_with_stock(jsonb, jsonb, uuid[]) to authenticated;

