-- set_item_customisations(p_item_id, p_links)
--   p_links = [{ "group_id": "...", "default_count": 2 }]: the groups ticked for ONE menu item (a number only for
--   counters). Groups that reach the item through its category are not listed here (a counter's number for
--   one of those is listed to give the item a number of its own).
create or replace function public.set_item_customisations(p_item_id uuid, p_links jsonb)
returns void
language plpgsql
set search_path = public
as $$
declare
  v_link jsonb;
begin
  if not public.is_manager() then
    raise exception 'Only managers can change customisations';
  end if;
  if jsonb_typeof(p_links) is distinct from 'array' then
    raise exception 'The customisations must be a list';
  end if;

  delete from public.modifier_group_links
  where menu_item_id = p_item_id
    and group_id not in (select (l ->> 'group_id')::uuid from jsonb_array_elements(p_links) l);

  for v_link in select * from jsonb_array_elements(p_links)
  loop
    insert into public.modifier_group_links (group_id, menu_item_id, default_count)
    values ((v_link ->> 'group_id')::uuid, p_item_id, nullif(v_link ->> 'default_count', '')::integer)
    on conflict (group_id, menu_item_id) where menu_item_id is not null do update set default_count = excluded.default_count;
  end loop;
end;
$$;

revoke all on function public.set_item_customisations(uuid, jsonb) from public, anon, authenticated;
grant execute on function public.set_item_customisations(uuid, jsonb) to authenticated;


