-- ---------------------------------------------------------------------
-- dashboard_summary(date): everything on the admin Dashboard for one business day ("On shift now" includes the kitchen)
-- ---------------------------------------------------------------------
create or replace function public.dashboard_summary(p_date date default public.dubai_today())
returns jsonb
language plpgsql
stable
as $$
declare
  v_is_today  boolean := p_date = public.dubai_today();
  v_now_hour  integer := extract(hour from now() at time zone 'Asia/Dubai')::int;
  v_summary   jsonb := public.sales_summary(p_date, p_date);
  v_opens     time;
  v_last_hour integer;
  v_hours     jsonb;
  v_top       jsonb;
  v_payments  jsonb;
  v_low_count integer;
  v_attention jsonb;
  v_shift     jsonb;
begin
  -- opening time: a special day's hours first, otherwise that weekday's hours from settings
  select sd.opens_at into v_opens from public.special_days sd where sd.date = p_date and not sd.closed;
  if v_opens is null then
    select (d ->> 'from')::time into v_opens
    from public.settings st, jsonb_array_elements(st.opening_hours -> 'days') d
    where d ->> 'day' = trim(to_char(p_date, 'FMDay')) and (d ->> 'open')::boolean;
  end if;

  -- sales for each hour, from 7am up to the last hour with sales (or the current hour today)
  select greatest(
           coalesce(max(extract(hour from created_at at time zone 'Asia/Dubai')::int), 7),
           case when v_is_today then v_now_hour else 7 end)
  into v_last_hour
  from public.orders where status = 'paid' and order_date = p_date;

  select coalesce(jsonb_agg(jsonb_build_object(
           'hour', h.hour,
           'amount', coalesce(a.amount, 0),
           'in_progress', v_is_today and h.hour = v_now_hour
         ) order by h.hour), '[]'::jsonb)
  into v_hours
  from generate_series(7, v_last_hour) as h(hour)
  left join (
    select extract(hour from created_at at time zone 'Asia/Dubai')::int as hour, sum(total) as amount
    from public.orders where status = 'paid' and order_date = p_date
    group by 1
  ) a on a.hour = h.hour;

  -- top 5 items by number sold
  select coalesce(jsonb_agg(jsonb_build_object('name', t.name, 'sold', t.sold) order by t.sold desc, t.name), '[]'::jsonb)
  into v_top
  from (
    select oi.name, sum(oi.quantity)::int as sold
    from public.order_items oi
    join public.orders o on o.id = oi.order_id
    where o.status = 'paid' and o.order_date = p_date
    group by oi.name
    order by sold desc, oi.name
    limit 5
  ) t;

  -- how people paid, plus discounts given and refunds
  select jsonb_build_object(
           'card',             coalesce(sum(total) filter (where status = 'paid' and payment_method = 'card'), 0),
           'cash',             coalesce(sum(total) filter (where status = 'paid' and payment_method = 'cash'), 0),
           'split',            coalesce(sum(total) filter (where status = 'paid' and payment_method = 'split'), 0),
           'card_count',       count(*) filter (where status = 'paid' and payment_method = 'card'),
           'cash_count',       count(*) filter (where status = 'paid' and payment_method = 'cash'),
           'split_count',      count(*) filter (where status = 'paid' and payment_method = 'split'),
           'discounts_count',  count(*) filter (where status = 'paid' and discount_amount > 0),
           'discounts_amount', coalesce(sum(discount_amount) filter (where status = 'paid'), 0),
           'refunds_count',    count(*) filter (where status = 'refunded'),
           'refunds_amount',   coalesce(sum(total) filter (where status = 'refunded'), 0)
         )
  into v_payments
  from public.orders where order_date = p_date;

  -- stock that is low or out (the 5 most urgent are listed)
  select count(*) into v_low_count from public.stock_items where quantity <= low_at;

  select coalesce(jsonb_agg(jsonb_build_object(
           'name', s.name,
           'status', case when s.quantity = 0 then 'out' else 'low' end,
           'quantity', s.quantity,
           'unit', s.unit
         ) order by s.rn), '[]'::jsonb)
  into v_attention
  from (
    select si.*, row_number() over (order by (si.quantity = 0) desc, si.quantity / nullif(si.low_at, 0), si.name) as rn
    from public.stock_items si
    where si.quantity <= si.low_at
  ) s
  where s.rn <= 5;

  -- staff with an open shift right now: who, where, since when, and how many orders they have taken on it
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', sh.id, 'name', st.name, 'role', st.role, 'counter_number', c.number, 'device', sh.device, 'started_at', sh.started_at,
           'orders', (select count(*) from public.orders o
                      where o.staff_id = sh.staff_id and o.counter_id = sh.counter_id and o.created_at >= sh.started_at)
         ) order by sh.started_at), '[]'::jsonb)
  into v_shift
  from public.shifts sh
  join public.staff st on st.id = sh.staff_id
  left join public.counters c on c.id = sh.counter_id
  where sh.ended_at is null and sh.started_at > now() - interval '16 hours';

  return jsonb_build_object(
    'date',                 p_date,
    'opens_at',             v_opens,
    'sales_today',          v_summary -> 'total_sales',
    'orders_today',         v_summary -> 'orders',
    'average_order',        v_summary -> 'average_order',
    'sales_change_percent', v_summary -> 'sales_change_percent',
    'orders_change',        v_summary -> 'orders_change',
    'compare_label',        v_summary -> 'compare_label',
    'low_stock_count',      v_low_count,
    'sales_by_hour',        v_hours,
    'top_items',            v_top,
    'payments',             v_payments,
    'needs_attention',      v_attention,
    'on_shift',             v_shift
  );
end;
$$;

revoke all on function public.dashboard_summary(date) from public, anon, authenticated;
grant execute on function public.dashboard_summary(date) to authenticated;

-- ---------------------------------------------------------------------
-- sales_summary: totals for p_from..p_to (inclusive), plus how they compare.
--   one day  -> compared with the same weekday last week ("last Wednesday")
--   a range  -> compared with the previous range of the same length
-- When the range includes today, the earlier period is cut at the same time
-- of day, so a half-finished day isn't compared with a whole one.
-- ---------------------------------------------------------------------
create or replace function public.sales_summary(p_from date, p_to date)
returns jsonb
language plpgsql
stable
as $$
declare
  v_today       date := public.dubai_today();
  v_span        integer := p_to - p_from + 1;
  v_prev_from   date;
  v_prev_to     date;
  v_label       text;
  v_cutoff      timestamptz;
  v_total       numeric(12,2);
  v_orders      integer;
  v_prev_total  numeric(12,2);
  v_prev_orders integer;
  v_best        jsonb;
begin
  if p_to < p_from then
    raise exception 'The end date can''t be before the start date';
  end if;

  if p_from = p_to then
    v_prev_from := p_from - 7;
    v_prev_to   := v_prev_from;
    v_label     := 'last ' || trim(to_char(v_prev_from, 'FMDay'));
  else
    v_prev_to   := p_from - 1;
    v_prev_from := v_prev_to - v_span + 1;
    v_label     := 'the previous ' || v_span || ' days';
  end if;

  v_cutoff := case when p_to = v_today then now() - (p_to - v_prev_to) * interval '1 day' end;

  select coalesce(sum(total), 0), count(*) into v_total, v_orders
  from public.orders
  where status = 'paid' and order_date between p_from and p_to;

  select coalesce(sum(total), 0), count(*) into v_prev_total, v_prev_orders
  from public.orders
  where status = 'paid'
    and order_date between v_prev_from and v_prev_to
    and (v_cutoff is null or created_at <= v_cutoff);

  select jsonb_build_object('name', b.name, 'sold', b.sold) into v_best
  from (
    select oi.name, sum(oi.quantity)::int as sold
    from public.order_items oi
    join public.orders o on o.id = oi.order_id
    where o.status = 'paid' and o.order_date between p_from and p_to
    group by oi.name
    order by sold desc, oi.name
    limit 1
  ) b;

  return jsonb_build_object(
    'total_sales',          v_total,
    'orders',               v_orders,
    'average_order',        case when v_orders > 0 then round(v_total / v_orders, 2) else 0 end,
    'best_seller',          v_best,
    'sales_change_percent', case when v_prev_total > 0
                                 then round((v_total - v_prev_total) / v_prev_total * 100, 1) end,
    'orders_change',        case when v_prev_orders > 0 then v_orders - v_prev_orders end,
    'compare_label',        v_label
  );
end;
$$;

revoke all on function public.sales_summary(date, date) from public, anon, authenticated;
grant execute on function public.sales_summary(date, date) to authenticated;


