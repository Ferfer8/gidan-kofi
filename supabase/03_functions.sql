-- get_pos_day_summary(token): today's takings for the session's counter
create or replace function public.get_pos_day_summary(p_token text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_s        record;
  v_today    date := public.business_today();
  v_counter  uuid;
  v_start    numeric;
  v_closing  jsonb;
  v_last     jsonb;
  v_totals   record;
