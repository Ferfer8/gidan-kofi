-- ---------------------------------------------------------------------
-- save_modifier_group(p_group)
--   { id (null = new), name, selection: 'single' | 'multiple' | 'counter', required,
--     counter_default, counter_min, counter_max, counter_price,
--     choices: [{ id (null = new), name, extra_price, is_default, available }]   (their order is the order on the POS)
--     category_ids: [...], item_links: [{ item_id, default_count }] }
--   Everything is saved or nothing is. Returns the group's id.
-- ---------------------------------------------------------------------
create or replace function public.save_modifier_group(p_group jsonb)
returns uuid
language plpgsql
set search_path = public
as $$
declare
  v_id      uuid := nullif(p_group ->> 'id', '')::uuid;
  v_name    text := btrim(coalesce(p_group ->> 'name', ''));
  v_sel     text := p_group ->> 'selection';
  v_min     integer := nullif(p_group ->> 'counter_min', '')::integer;
  v_max     integer := nullif(p_group ->> 'counter_max', '')::integer;
  v_def     integer := nullif(p_group ->> 'counter_default', '')::integer;
  v_price   numeric := nullif(p_group ->> 'counter_price', '')::numeric;
  v_choice  jsonb;
  v_cid     uuid;
  v_kept    uuid[] := '{}';
  v_names   text[] := '{}';
  v_index   integer := 0;
  v_default_seen boolean := false;
  v_is_default boolean;
  v_link    jsonb;
  v_cat     text;
begin
  if not public.is_manager() then
    raise exception 'Only managers can change customisations';
  end if;
  if v_name = '' then
    raise exception 'Give the group a name';
  end if;
  if v_sel is null or v_sel not in ('single', 'multiple', 'counter') then
    raise exception 'Choose a type for the group';
  end if;
  if exists (select 1 from public.modifier_groups where lower(name) = lower(v_name) and id is distinct from v_id) then
    raise exception 'There is already a group called %', v_name;
  end if;

  if v_sel = 'counter' then
    if v_min is null or v_max is null or v_def is null or v_min < 0 or v_max < v_min or v_def < v_min or v_def > v_max then
      raise exception 'The default must be between the minimum and the maximum';
    end if;
    if coalesce(v_price, 0) < 0 then
      raise exception 'The extra price can''t be less than 0';
    end if;
  else
    if jsonb_typeof(p_group -> 'choices') is distinct from 'array' or jsonb_array_length(p_group -> 'choices') = 0 then
      raise exception 'Add at least one choice';
    end if;
    for v_choice in select * from jsonb_array_elements(p_group -> 'choices')
    loop
      if btrim(coalesce(v_choice ->> 'name', '')) = '' then
        raise exception 'Every choice needs a name';
      end if;
      if lower(btrim(v_choice ->> 'name')) = any (v_names) then
        raise exception 'There are two choices called %', btrim(v_choice ->> 'name');
      end if;
      if coalesce((v_choice ->> 'extra_price')::numeric, 0) < 0 then
        raise exception 'An extra price can''t be less than 0';
      end if;
      v_names := v_names || lower(btrim(v_choice ->> 'name'));
    end loop;
  end if;

  -- the group
  if v_id is null then
    insert into public.modifier_groups (name, selection, required, sort_order, counter_default, counter_min, counter_max, counter_price)
    values (v_name, v_sel, v_sel = 'single' and coalesce((p_group ->> 'required')::boolean, false),
            (select coalesce(max(sort_order), 0) + 1 from public.modifier_groups),
            case when v_sel = 'counter' then v_def end, case when v_sel = 'counter' then v_min end,
            case when v_sel = 'counter' then v_max end, case when v_sel = 'counter' then coalesce(v_price, 0) end)
    returning id into v_id;
  else
    update public.modifier_groups
    set name = v_name, selection = v_sel, required = (v_sel = 'single' and coalesce((p_group ->> 'required')::boolean, false)),
        counter_default = case when v_sel = 'counter' then v_def end, counter_min = case when v_sel = 'counter' then v_min end,
        counter_max = case when v_sel = 'counter' then v_max end, counter_price = case when v_sel = 'counter' then coalesce(v_price, 0) end
    where id = v_id;
    if not found then
      raise exception 'That group no longer exists';
    end if;
  end if;

  -- the choices (a counter has none)
  if v_sel = 'counter' then
    delete from public.modifiers where group_id = v_id;
  else
    -- park the names of the choices that stay, so two choices can swap names in one save
    update public.modifiers set name = '~' || id::text
    where group_id = v_id and id in (select (c ->> 'id')::uuid from jsonb_array_elements(p_group -> 'choices') c where nullif(c ->> 'id', '') is not null);

    for v_choice in select * from jsonb_array_elements(p_group -> 'choices')
    loop
      v_index := v_index + 1;
      v_is_default := coalesce((v_choice ->> 'is_default')::boolean, false);
      if v_sel = 'single' then               -- a single choice has one default at most
        v_is_default := v_is_default and not v_default_seen;
        v_default_seen := v_default_seen or v_is_default;
      end if;

      v_cid := nullif(v_choice ->> 'id', '')::uuid;
      if v_cid is not null and exists (select 1 from public.modifiers where id = v_cid and group_id = v_id) then
        update public.modifiers
        set name = btrim(v_choice ->> 'name'), extra_price = coalesce((v_choice ->> 'extra_price')::numeric, 0), is_default = v_is_default,
            available = coalesce((v_choice ->> 'available')::boolean, true), sort_order = v_index
        where id = v_cid;
      else
        insert into public.modifiers (group_id, name, extra_price, is_default, available, sort_order)
        values (v_id, btrim(v_choice ->> 'name'), coalesce((v_choice ->> 'extra_price')::numeric, 0), v_is_default,
                coalesce((v_choice ->> 'available')::boolean, true), v_index)
        returning id into v_cid;
      end if;
      v_kept := v_kept || v_cid;
    end loop;

    delete from public.modifiers where group_id = v_id and id <> all (v_kept);
  end if;

  -- what it applies to: whole categories, and single items (an item in a chosen category is only kept
  -- when it has a number of its own)
  delete from public.modifier_group_links where group_id = v_id;
  if jsonb_typeof(p_group -> 'category_ids') = 'array' then
    insert into public.modifier_group_links (group_id, category_id)
    select v_id, c::uuid from jsonb_array_elements_text(p_group -> 'category_ids') c;
  end if;
  if jsonb_typeof(p_group -> 'item_links') = 'array' then
    for v_link in select * from jsonb_array_elements(p_group -> 'item_links')
    loop
      insert into public.modifier_group_links (group_id, menu_item_id, default_count)
      select v_id, m.id, case when v_sel = 'counter' then nullif(v_link ->> 'default_count', '')::integer end
      from public.menu_items m
      where m.id = (v_link ->> 'item_id')::uuid
        and (nullif(v_link ->> 'default_count', '') is not null
             or not exists (select 1 from public.modifier_group_links k where k.group_id = v_id and k.category_id = m.category_id))
      on conflict (group_id, menu_item_id) where menu_item_id is not null do nothing;
    end loop;
  end if;

  return v_id;
end;
$$;

revoke all on function public.save_modifier_group(jsonb) from public, anon, authenticated;
grant execute on function public.save_modifier_group(jsonb) to authenticated;

