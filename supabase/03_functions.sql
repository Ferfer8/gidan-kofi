-- =====================================================================
-- 03_functions.sql
-- All the database functions: the POS (menu, checkout, refunds, end of day, PIN sign-in),
-- the kitchen, the business day, the admin panel (menu/stock save, imports, customisations,
-- reports) and the "permanent code" triggers.
--
-- Run this THIRD (after 01_schema.sql and 02_security.sql). Safe to run again: every
-- function is "create or replace", and the grants are repeated.
--
-- Most functions are SECURITY DEFINER: they run with the rights of the database owner and
-- check who is asking themselves (a manager is signed in, or a valid session token is given).
-- Not-signed-in callers (role anon) can only call get_pos_menu, ping, get_pos_counters and
-- sign_in_with_pin freely; the other POS functions are open to anon only because they refuse
-- to do anything without a valid session token.
-- The apps call them through supabase.rpc(). The grants under each function say who may call it.
-- (is_manager() is in 02_security.sql because the security rules need it first.)
-- =====================================================================

-- ---------------------------------------------------------------------
-- Business day
-- Late-night trading counts as the previous day. The cut-off time is in settings
-- (opening_hours.businessDayEnds, default 04:00); the time zone is settings.details.timeZone.
-- ---------------------------------------------------------------------

create or replace function public.business_time_zone()
returns text
language sql
stable
as $$
  select coalesce(nullif((select details ->> 'timeZone' from public.settings limit 1), ''), 'Asia/Dubai');
$$;

revoke all on function public.business_time_zone() from public, anon, authenticated;
grant execute on function public.business_time_zone() to authenticated;

-- "04:00" (anything that isn't HH:MM is ignored)
create or replace function public.business_day_ends()
returns text
language sql
stable
as $$
  select case
           when (select opening_hours ->> 'businessDayEnds' from public.settings limit 1) ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
             then (select opening_hours ->> 'businessDayEnds' from public.settings limit 1)
           else '04:00'
         end;
$$;

revoke all on function public.business_day_ends() from public, anon, authenticated;
grant execute on function public.business_day_ends() to authenticated;

-- business_date(ts): the business day a moment belongs to (a date). The clock is moved back by the "day ends at"
-- time and then the date is taken, so with 04:00 a sale at 00:10 on Sunday counts for Saturday.
create or replace function public.business_date(ts timestamptz default now())
returns date
language sql
stable
as $$
  select ((ts at time zone public.business_time_zone()) - public.business_day_ends()::interval)::date;
$$;

revoke all on function public.business_date(timestamp with time zone) from public, anon, authenticated;
grant execute on function public.business_date(timestamp with time zone) to authenticated;

create or replace function public.business_today()
returns date
language sql
stable
as $$
  select public.business_date(now());
$$;

revoke all on function public.business_today() from public, anon, authenticated;
grant execute on function public.business_today() to authenticated;

