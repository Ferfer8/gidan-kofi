create or replace function public.import_menu_items(p_items jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_item      jsonb;
  v_option    jsonb;
  v_id        uuid;
  v_name      text;
  v_tracking  text;
  v_category  uuid;
  v_allergens text[];
  v_served    text;
  v_cold_extra numeric;
  v_is_drink  boolean;
  v_size_id   uuid;
  v_label     text;
  v_stock_id  uuid;
  v_type      text;
  v_wanted    text;
  v_added     int := 0;
  v_updated   int := 0;
  v_created   int := 0;
begin
  if not public.is_manager() then
    raise exception 'Only managers can import the menu';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Nothing to import';
  end if;
  if jsonb_array_length(p_items) > 1000 then
    raise exception 'A file can have at most 1,000 items';
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_id := nullif(v_item ->> 'id', '')::uuid;
    v_name := btrim(v_item ->> 'name');
    v_tracking := coalesce(v_item ->> 'tracking', 'none');
    v_category := (v_item ->> 'category_id')::uuid;
    v_allergens := coalesce(array(select jsonb_array_elements_text(coalesce(v_item -> 'allergens', '[]'::jsonb))), '{}');

    if v_name is null or v_name = '' then
      raise exception 'An item has no name';
    end if;
    if v_tracking not in ('none', 'stock', 'made_daily') then
      raise exception 'Unknown way of tracking "%" (%)', v_tracking, v_name;
    end if;
    -- "Served" is only for drinks: other items have no served setting and no extra for cold
    select exists (select 1 from public.categories where id = v_category and name = 'Drinks') into v_is_drink;
    v_served := nullif(v_item ->> 'served', '');
    v_cold_extra := coalesce(nullif(v_item ->> 'cold_extra', '')::numeric, 0);
    if v_is_drink then
      if v_served is null or v_served not in ('hot', 'cold', 'both') then
        raise exception 'Choose Hot, Cold or Hot & cold for %', v_name;
      end if;
      if v_served <> 'both' then
        v_cold_extra := 0;
      end if;
    else
      v_served := null;
      v_cold_extra := 0;
    end if;
    if v_cold_extra < 0 then
      raise exception 'The extra for cold of % cannot be below 0', v_name;
    end if;
    if jsonb_typeof(v_item -> 'options') is distinct from 'array' or jsonb_array_length(v_item -> 'options') = 0 then
      raise exception '% needs at least one size or colour', v_name;
    end if;

    -- the item
    if v_id is null then
      insert into public.menu_items (category_id, name, description, allergens, on_menu, tracking, sort_order, served, cold_extra)
      values (
        v_category, v_name, nullif(v_item ->> 'description', ''), v_allergens,
        coalesce((v_item ->> 'on_menu')::boolean, true), v_tracking,
        (select coalesce(max(sort_order), 0) + 1 from public.menu_items where category_id = v_category),
        v_served, v_cold_extra
      )
      returning id into v_id;
      v_added := v_added + 1;
    else
      update public.menu_items
      set category_id = v_category,
          name = v_name,
          description = nullif(v_item ->> 'description', ''),
          allergens = v_allergens,
          on_menu = coalesce((v_item ->> 'on_menu')::boolean, true),
          tracking = v_tracking,
          served = v_served,
          cold_extra = v_cold_extra
      where id = v_id;
      if not found then
        raise exception '% no longer exists. Nothing was changed.', v_name;
      end if;
      v_updated := v_updated + 1;
    end if;

    -- links that no longer make sense for the way the item is tracked
    v_wanted := case v_tracking when 'stock' then 'retail' when 'made_daily' then 'frozen_bakery' else null end;
    update public.item_sizes s
    set stock_item_id = null
    where s.menu_item_id = v_id
      and s.stock_item_id is not null
      and not exists (select 1 from public.stock_items f where f.id = s.stock_item_id and f.type = v_wanted);

    -- the options
    for v_option in select value from jsonb_array_elements(v_item -> 'options') loop
      v_label := btrim(v_option ->> 'label');
      if v_label is null or v_label = '' then
        raise exception '% has an option with no name', v_name;
      end if;
      if (v_option ->> 'price') is null or (v_option ->> 'price')::numeric <= 0 then
        raise exception 'The price of % (%) must be above 0', v_label, v_name;
      end if;

      select id into v_size_id from public.item_sizes
      where menu_item_id = v_id and lower(label) = lower(v_label);

      if v_size_id is null then
        insert into public.item_sizes (menu_item_id, label, price, sort_order)
        values (
          v_id, v_label, (v_option ->> 'price')::numeric,
          (select coalesce(max(sort_order), 0) + 1 from public.item_sizes where menu_item_id = v_id)
        )
        returning id into v_size_id;
      else
        update public.item_sizes set price = (v_option ->> 'price')::numeric where id = v_size_id;
      end if;

      -- its stock link
      v_stock_id := nullif(v_option ->> 'stock_item_id', '')::uuid;

      if v_tracking = 'none' then
        v_stock_id := null;
      else
        if v_stock_id is null and v_tracking = 'stock' then
          if coalesce((v_option ->> 'create_stock')::boolean, false) then
            insert into public.stock_items (name, type, unit, quantity, low_at)
            values (
              case when lower(v_label) = 'regular' then v_name else v_name || ' · ' || v_label end,
              'retail', 'pcs', 0, 0
            )
            returning id into v_stock_id;
            v_created := v_created + 1;
          else
            -- no stock item given: keep the one the option already has, if there is one
            select stock_item_id into v_stock_id from public.item_sizes where id = v_size_id;
            if v_stock_id is null then
              raise exception '% (%) needs a stock item', v_label, v_name;
            end if;
          end if;
        end if;

        if v_stock_id is not null then
          select type into v_type from public.stock_items where id = v_stock_id;
          if v_type is null then
            raise exception 'The stock item for % (%) does not exist', v_label, v_name;
          end if;
          if v_type is distinct from v_wanted then
            raise exception 'The stock item for % (%) must be % stock', v_label, v_name,
              case v_tracking when 'stock' then 'Retail' else 'Frozen bakery' end;
          end if;
          if exists (select 1 from public.item_sizes where stock_item_id = v_stock_id and id <> v_size_id) then
            raise exception 'The stock item for % (%) is already used by another menu option', v_label, v_name;
          end if;
        end if;
      end if;

      if v_stock_id is not null then
        update public.item_sizes set stock_item_id = v_stock_id where id = v_size_id;
      end if;
    end loop;
  end loop;

  return jsonb_build_object('added', v_added, 'updated', v_updated, 'created_stock', v_created);
end;
$$;

revoke all on function public.import_menu_items(jsonb) from public, anon, authenticated;
grant execute on function public.import_menu_items(jsonb) to authenticated;

create or replace function public.import_stock_items(p_rows jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_added   int := 0;
  v_updated int := 0;
  v_expect  int;
begin
  if not public.is_manager() then
    raise exception 'Only managers can import stock';
  end if;

  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then
    raise exception 'Nothing to import';
  end if;
  if jsonb_array_length(p_rows) > 1000 then
    raise exception 'A file can have at most 1,000 rows';
  end if;

  -- (no temporary table: the signed-in role does not need any extra permission)
  -- updates
  select count(*) into v_expect
  from jsonb_to_recordset(p_rows) as r(id uuid)
  where r.id is not null;

  update public.stock_items s
  set name      = r.name,
      type      = r.type,
      pack_type = r.pack_type,
      pack_size = r.pack_size,
      pack_unit = r.pack_unit,
      unit      = r.unit,
      quantity  = r.quantity,
      low_at    = r.low_at,
      cost      = r.cost,
      supplier  = nullif(r.supplier, ''),
      sku       = nullif(r.sku, '')
  from jsonb_to_recordset(p_rows) as r(
    id uuid, name text, type text, pack_type text, pack_size numeric, pack_unit text, unit text,
    quantity numeric, low_at numeric, cost numeric, supplier text, sku text
  )
  where r.id is not null and s.id = r.id;
  get diagnostics v_updated = row_count;

  if v_updated <> v_expect then
    raise exception 'Some stock items in the file no longer exist. Nothing was changed.';
  end if;

  -- new items (the code comes from the sequence)
  insert into public.stock_items (name, type, pack_type, pack_size, pack_unit, unit, quantity, low_at, cost, supplier, sku)
  select r.name, r.type, r.pack_type, r.pack_size, r.pack_unit, r.unit, r.quantity, r.low_at, r.cost,
         nullif(r.supplier, ''), nullif(r.sku, '')
  from jsonb_to_recordset(p_rows) as r(
    id uuid, name text, type text, pack_type text, pack_size numeric, pack_unit text, unit text,
    quantity numeric, low_at numeric, cost numeric, supplier text, sku text
  )
  where r.id is null;
  get diagnostics v_added = row_count;

  return jsonb_build_object('added', v_added, 'updated', v_updated);
end;
$$;

