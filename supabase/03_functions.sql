-- ---------------------------------------------------------------------
-- PINs, staff sign-in and shifts
-- Staff PINs are bcrypt hashes; they are only ever checked in these functions. Signing in starts a shift and returns a secret session token (only its hash is stored); every POS function takes that token and finds out who is asking from it (require_session). Wrong PINs are counted in pin_attempts and lock the device or the shift for 5 minutes. A manager PIN gives a one-time approval token (2 minutes) that refunds, manual discounts and reopening the day use up.
-- ---------------------------------------------------------------------

-- A random 4-digit PIN (1000-9999) that no active staff member uses. Managers only.
create or replace function public.generate_free_pin()
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_pin text;
  v_tries integer := 0;
begin
  if not public.is_manager() then
    raise exception 'Only managers can generate PINs';
  end if;

  loop
    v_pin := (1000 + floor(random() * 9000))::int::text;
    exit when not exists (
      select 1 from public.staff where status = 'active' and pin_hash is not null and pin_hash = crypt(v_pin, pin_hash)
    );
    v_tries := v_tries + 1;
    if v_tries > 200 then raise exception 'No free PIN left'; end if;
  end loop;
  return v_pin;
end;
$$;

revoke all on function public.generate_free_pin() from public, anon, authenticated;
grant execute on function public.generate_free_pin() to authenticated;

-- set_staff_pin: a manager types a 4-digit PIN for someone. Switched off for the demo login (PT411): there
-- the "PIN already used" answer would show which PINs are taken.
create or replace function public.set_staff_pin(p_staff_id uuid, p_pin text)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not public.is_manager() then
    raise exception 'Only managers can set PINs';
  end if;

  if public.is_demo_user() then
    raise exception 'In the demo, PINs are generated by the system' using errcode = 'PT411';
  end if;

  if p_pin !~ '^[0-9]{4}$' then
    raise exception 'A PIN must be exactly 4 digits';
  end if;

  if exists (
    select 1 from public.staff
    where id <> p_staff_id and status = 'active' and pin_hash is not null and pin_hash = crypt(p_pin, pin_hash)
  ) then
    raise exception 'That PIN is already used by someone else. Choose another.';
  end if;

  update public.staff
  set pin_hash = crypt(p_pin, gen_salt('bf'))
  where id = p_staff_id;

  if not found then
    raise exception 'Staff member not found';
  end if;
end;
$$;

revoke all on function public.set_staff_pin(uuid, text) from public, anon, authenticated;
grant execute on function public.set_staff_pin(uuid, text) to authenticated;

-- reset_staff_pin(staff id): gives the person a new random 4-digit PIN that nobody else uses, saves it (only the
-- hash is stored) and returns it once, so it can be written down. Managers only. The demo login can use it
-- for the staff it added, but not for protected staff.
create or replace function public.reset_staff_pin(p_staff_id uuid)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_pin   text;
  v_tries integer := 0;
begin
  if not public.is_manager() then
    raise exception 'Only managers can set PINs';
  end if;
  if not exists (select 1 from public.staff where id = p_staff_id) then
    raise exception 'Staff member not found';
  end if;
  if public.is_demo_user() and exists (select 1 from public.staff where id = p_staff_id and is_demo_protected) then
    raise exception 'Existing staff can''t be changed in the demo' using errcode = 'PT410';
  end if;

  loop
    v_pin := (1000 + floor(random() * 9000))::int::text;
    exit when not exists (
      select 1 from public.staff where status = 'active' and pin_hash is not null and pin_hash = crypt(v_pin, pin_hash)
    );
    v_tries := v_tries + 1;
    if v_tries > 200 then raise exception 'No free PIN left'; end if;
  end loop;

  update public.staff set pin_hash = crypt(v_pin, gen_salt('bf')) where id = p_staff_id;
  return v_pin;
end;
$$;

revoke all on function public.reset_staff_pin(uuid) from public, anon, authenticated;
grant execute on function public.reset_staff_pin(uuid) to authenticated;

-- verify_staff_pin: is this the right PIN for an active staff member? Always "no" for the demo login, so it
-- can not be used to try PINs.
