-- =====================================================================
-- 08_demo_support.sql
-- Structure, security rules and functions that let a public demo be tried safely. They only act when the
-- signed-in manager is flagged as the demo login (staff.is_demo_login), so a normal café is not affected.
-- The flags themselves, the Demo Manager and the nightly reset are data and live in a private demo setup
-- file, not here.
--
-- Run this on a database that was set up with the earlier files. It is safe to run more than once.
-- (A new setup does not need it: 01 to 04 already contain everything in it.)
--
-- What it adds:
--   1. Three flags on staff: is_demo_protected (existing staff the demo can not change), is_demo_login (the
--      manager whose login is the demo login) and added_in_demo (staff added by visitors).
--   2. is_demo_user(): true when the signed-in manager is the demo login.
--   3. A guard on the staff table: the demo login can add staff (marked added_in_demo) and change or remove
--      those, but can not change, remove or re-PIN protected staff. Error code PT410.
--   4. PINs are only ever generated by the system for the demo login (reset_staff_pin). Typing a PIN
--      (set_staff_pin) and testing a PIN (verify_staff_pin) are switched off for it, so it can not be used to
--      find out other people's PINs. Error code PT411.
--   5. Staff e-mails are no longer readable straight from the table. The admin panel reads the staff list
--      through admin_list_staff() and its own record through my_staff_record(); the demo login does not see
--      other managers' e-mails.
--   6. The demo login can not delete files from the menu-images bucket (so a nightly reset can restore them).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. Flags on staff
-- ---------------------------------------------------------------------
alter table public.staff add column if not exists is_demo_protected boolean not null default false;
alter table public.staff add column if not exists is_demo_login boolean not null default false;
alter table public.staff add column if not exists added_in_demo boolean not null default false;


-- ---------------------------------------------------------------------
-- 2. Who is the demo login?
-- ---------------------------------------------------------------------

-- is_demo_user(): true when the signed-in Supabase user is an active manager flagged as the demo login.
create or replace function public.is_demo_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.staff
    where is_demo_login
      and role = 'manager'
      and status = 'active'
      and email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.is_demo_user() from public, anon, authenticated;
grant execute on function public.is_demo_user() to authenticated;


-- ---------------------------------------------------------------------
-- 3. The staff guard
-- ---------------------------------------------------------------------

-- staff_demo_guard(): runs before every insert, update and delete on staff. Nothing changes unless the
-- signed-in manager is the demo login. For the demo login:
--   * a new row is marked added_in_demo and is never protected
--   * protected rows can not be changed or removed (only the sign-in bookkeeping, last_active_at, may change,
--     because signing in on the POS updates it from the same browser)
--   * the three flags can never be changed
create or replace function public.staff_demo_guard()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if not public.is_demo_user() then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.is_demo_protected := false;
    new.is_demo_login := false;
    new.added_in_demo := true;
    return new;
  end if;

  if old.is_demo_protected then
    if tg_op = 'DELETE' or
       (new.name, new.role, new.email, new.status, new.since, new.permissions, new.pin_hash,
        new.is_demo_protected, new.is_demo_login, new.added_in_demo)
       is distinct from
       (old.name, old.role, old.email, old.status, old.since, old.permissions, old.pin_hash,
        old.is_demo_protected, old.is_demo_login, old.added_in_demo) then
      raise exception 'Existing staff can''t be changed in the demo' using errcode = 'PT410';
    end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  new.is_demo_protected := old.is_demo_protected;
  new.is_demo_login := old.is_demo_login;
  new.added_in_demo := old.added_in_demo;
  return new;
end;
$$;

revoke all on function public.staff_demo_guard() from public, anon, authenticated;

drop trigger if exists staff_demo_guard on public.staff;
create trigger staff_demo_guard before insert or update or delete on public.staff
  for each row execute function public.staff_demo_guard();


-- ---------------------------------------------------------------------
-- 4. PINs
-- ---------------------------------------------------------------------

-- set_staff_pin: a manager types a 4-digit PIN for someone. Switched off for the demo login (PT411): there
-- the "PIN already used" answer would show which PINs are taken.
create or replace function public.set_staff_pin(p_staff_id uuid, p_pin text)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not public.is_manager() then
    raise exception 'Only managers can set PINs';
  end if;

  if public.is_demo_user() then
    raise exception 'In the demo, PINs are generated by the system' using errcode = 'PT411';
  end if;

  if p_pin !~ '^[0-9]{4}$' then
    raise exception 'A PIN must be exactly 4 digits';
  end if;

  if exists (
    select 1 from public.staff
    where id <> p_staff_id and status = 'active' and pin_hash is not null and pin_hash = crypt(p_pin, pin_hash)
  ) then
    raise exception 'That PIN is already used by someone else. Choose another.';
  end if;

  update public.staff
  set pin_hash = crypt(p_pin, gen_salt('bf'))
  where id = p_staff_id;

  if not found then
    raise exception 'Staff member not found';
  end if;
end;
$$;

revoke all on function public.set_staff_pin(uuid, text) from public, anon, authenticated;
grant execute on function public.set_staff_pin(uuid, text) to authenticated;

-- reset_staff_pin(staff id): gives the person a new random 4-digit PIN that nobody else uses, saves it (only the
-- hash is stored) and returns it once, so it can be written down. Managers only. The demo login can use it
-- for the staff it added, but not for protected staff.
create or replace function public.reset_staff_pin(p_staff_id uuid)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_pin   text;
  v_tries integer := 0;
begin
  if not public.is_manager() then
    raise exception 'Only managers can set PINs';
  end if;
  if not exists (select 1 from public.staff where id = p_staff_id) then
    raise exception 'Staff member not found';
  end if;
  if public.is_demo_user() and exists (select 1 from public.staff where id = p_staff_id and is_demo_protected) then
    raise exception 'Existing staff can''t be changed in the demo' using errcode = 'PT410';
  end if;

  loop
    v_pin := (1000 + floor(random() * 9000))::int::text;
    exit when not exists (
      select 1 from public.staff where status = 'active' and pin_hash is not null and pin_hash = crypt(v_pin, pin_hash)
    );
    v_tries := v_tries + 1;
    if v_tries > 200 then raise exception 'No free PIN left'; end if;
  end loop;

  update public.staff set pin_hash = crypt(v_pin, gen_salt('bf')) where id = p_staff_id;
  return v_pin;
end;
$$;

revoke all on function public.reset_staff_pin(uuid) from public, anon, authenticated;
grant execute on function public.reset_staff_pin(uuid) to authenticated;

-- verify_staff_pin: is this the right PIN for an active staff member? Always "no" for the demo login, so it
-- can not be used to try PINs.
create or replace function public.verify_staff_pin(p_staff_id uuid, p_pin text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions
as $$
  select coalesce(
    (select pin_hash = crypt(p_pin, pin_hash)
     from public.staff
     where id = p_staff_id and status = 'active' and pin_hash is not null and not public.is_demo_user()),
    false
  );
$$;

revoke all on function public.verify_staff_pin(uuid, text) from public, anon, authenticated;
grant execute on function public.verify_staff_pin(uuid, text) to authenticated;


-- ---------------------------------------------------------------------
-- 5. Reading staff
-- ---------------------------------------------------------------------

-- The e-mail column is closed to direct reads and writes of the PIN hash and the flags stay with the owner;
-- managers can still add and change the other columns.
revoke insert, update on public.staff from authenticated;
revoke select (email) on public.staff from authenticated;
grant insert (name, role, email, permissions, status, since) on public.staff to authenticated;
grant update (name, role, email, permissions, status, since, last_active_at) on public.staff to authenticated;

-- admin_list_staff(): the staff list for the admin panel. Managers only. The demo login does not get the e-mail
-- of any manager but itself.
create or replace function public.admin_list_staff()
returns table (
  id uuid, name text, role text, email text, status text, since date, last_active_at timestamptz,
  permissions text[], is_demo_protected boolean, added_in_demo boolean
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_own text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_demo boolean;
begin
  if not public.is_manager() then
    raise exception 'Only managers can see the staff list';
  end if;
  v_demo := public.is_demo_user();

  return query
  select s.id, s.name, s.role, case when v_demo and s.email is distinct from v_own then null else s.email end,
         s.status, s.since, s.last_active_at, s.permissions, s.is_demo_protected, s.added_in_demo
  from public.staff s
  order by s.name;
end;
$$;

revoke all on function public.admin_list_staff() from public, anon, authenticated;
grant execute on function public.admin_list_staff() to authenticated;

-- my_staff_record(): the active manager row of the signed-in user (nothing for anyone else). The admin panel
-- uses it right after sign-in to check the account is a manager.
create or replace function public.my_staff_record()
returns table (id uuid, name text, role text, email text, status text)
language sql
stable
security definer
set search_path = public
as $$
  select s.id, s.name, s.role, s.email, s.status
  from public.staff s
  where s.role = 'manager'
    and s.status = 'active'
    and s.email = lower(coalesce(auth.jwt() ->> 'email', ''));
$$;

revoke all on function public.my_staff_record() from public, anon, authenticated;
grant execute on function public.my_staff_record() to authenticated;


-- ---------------------------------------------------------------------
-- 6. Menu images: the demo login can not delete files
-- ---------------------------------------------------------------------
drop policy if exists "Managers can delete menu images" on storage.objects;
create policy "Managers can delete menu images" on storage.objects
  for delete to authenticated
  using (bucket_id = 'menu-images' and public.is_manager() and not public.is_demo_user());
